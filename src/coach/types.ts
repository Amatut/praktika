// Короткая обратная связь наставника в режиме «Подсказки курса».
// Формат: где → почему → попробуй → проверь.

export type FeedbackSource =
  | 'mistake' // заранее написанный разбор типичной ошибки из материалов урока
  | 'compile' // синтаксическая ошибка
  | 'runtime' // ошибка во время выполнения
  | 'check' // ошибка в самой проверке: например, нет функции с нужным именем
  | 'rule' // требование к устройству кода (например, «используй цикл»)
  | 'output' // вывод не совпал с ожидаемым
  | 'timeout' // программа работала слишком долго
  | 'limit' // слишком много вывода
  | 'environment'; // ограничение браузерной среды, а не ошибка ученика

export interface Feedback {
  source: FeedbackSource;
  /** Короткий заголовок: «Незакрытая строка», «Не хватает строки». */
  title: string;
  /** Где: «Строка 2: print("Привет)» или «Тест „Пример 2“ (ввод: 7)». */
  where: string | null;
  why: string;
  tryThis: string;
  verify: string | null;
  /** Исходное сообщение Python — показывается по кнопке «Исходное сообщение». */
  raw: string | null;
  /** Строка кода для подсветки в редакторе. */
  line: number | null;
  testId: string | null;
  /** id разбора из материалов, если сработал заранее написанный разбор. */
  mistakeId: string | null;
}

/** Краткая категория ошибки для экрана «Прогресс» (повторяющиеся ошибки). */
export interface ErrorCategory {
  key: string;
  label: string;
}
